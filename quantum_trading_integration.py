"""
quantum_trading_integration.py
===============================
QuantumTrader: Executes trades using quantum signals generated by QuantumAnalyzer.
"""

from __future__ import annotations
from typing import Dict, Any
from datetime import datetime
import os
import csv

try:
    from binance.client import Client
except ImportError:
    Client = None

from quantum_engine import QuantumAnalyzer
from trade_executor import TradeExecutor
from position_monitor import PositionMonitor
from risk_manager import RiskManager


class QuantumTrader:
    """Quantum-driven trading interface for manual or auto execution."""

    def __init__(self, client: Client, log_dir: str = "logs"):
        self.client = client
        self.analyzer = QuantumAnalyzer()
        self.trade_executor = TradeExecutor(client, RiskManager())
        self.position_monitor = PositionMonitor()
        self.log_file = os.path.join(log_dir, "quantum_trades.csv")
        os.makedirs(log_dir, exist_ok=True)

    def evaluate_signal(self, market_data: Dict[str, Any]) -> Dict[str, Any]:
        """
        Generate a quantum-based decision from current market data.
        """
        return self.analyzer.generate_quantum_signal(market_data)

    def execute_quantum_trade(self, symbol: str, market_data: Dict[str, Any], quantity: float) -> Dict[str, Any]:
        """
        Executes a trade based on quantum signal.
        :param symbol: e.g. "BTCUSDT"
        :param market_data: dict of indicators
        :param quantity: float
        """
        signal = self.evaluate_signal(market_data)
        decision = signal["decision"]

        result = None
        if decision == "BUY":
            result = self.trade_executor.manual_trade(symbol, quantity, "BUY")
            if result.get("status") == "SUCCESS":
                self.position_monitor.add_position(symbol, {
                    "side": "BUY",
                    "qty": quantity,
                    "opened_at": datetime.now().isoformat(),
                    "decision": "Quantum BUY"
                })
        elif decision == "SELL":
            result = self.trade_executor.manual_trade(symbol, quantity, "SELL")
            if result.get("status") == "SUCCESS":
                self.position_monitor.remove(symbol)
        else:
            result = {"status": "SKIPPED", "reason": "HOLD signal"}

        self._log_trade(symbol, decision, quantity, signal)
        return {"signal": signal, "trade_result": result}

    def _log_trade(self, symbol: str, decision: str, qty: float, signal: Dict[str, Any]):
        """
        Logs each quantum trade for audit.
        """
        log_exists = os.path.isfile(self.log_file)
        with open(self.log_file, "a", newline="") as f:
            writer = csv.writer(f)
            if not log_exists:
                writer.writerow(["timestamp", "symbol", "decision", "quantity", "distribution", "confidence"])
            writer.writerow([
                datetime.now().isoformat(),
                symbol,
                decision,
                qty,
                signal.get("distribution"),
                signal.get("confidence")
            ])